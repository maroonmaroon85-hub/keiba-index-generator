def band_of(o, bands):
    for i, b in enumerate(bands):
        if b[1] <= o < b[2]:
            return i
    return -1


def roi_of(pay):
    """1点100円・n点買ったときのROI[%]。"""
    return 100.0 * np.sum(pay) / (COST * len(pay)) if len(pay) else float("nan")


def gate1(races):
    """(88)③④を別パーサで再現する。戻り値 (通ったか, 狭帯だけ落ちたか, 行)。"""
    acc = {b[0]: [] for b in GATE_BANDS}
    for r in races:
        for u, o, _ in r["horses"]:
            i = band_of(o, GATE_BANDS)
            if i < 0:
                continue
            v = payoff(r, "単勝", [u])
            if v is not None:
                acc[GATE_BANDS[i][0]].append(v)
    rows, bad = [], []
    for nm, lo, hi, known in GATE_BANDS:
        pay = np.asarray(acc[nm], float)
        roi = roi_of(pay)
        ok = abs(roi - known) <= GATE_TOL
        rows.append((nm, len(pay), roi, known, roi - known, ok))
        if not ok:
            bad.append(nm)
    return rows, bad


def cell_stats(pay, z):
    """1群の (n, ROI%, 平均損益円, 円の標準誤差)。"""
    n = len(pay)
    if n < 2:
        return n, float("nan"), float("nan"), float("nan")
    prof = pay - COST
    return n, roi_of(pay), float(prof.mean()), float(prof.std(ddof=1) / math.sqrt(n))


def selftest():
    """道具の自己テスト（(161)の手本）。データが無くても回る。"""
    ok = True
    # band_of
    assert band_of(2.9, BANDS) == 0 and band_of(3.0, BANDS) == 1
    assert band_of(49.9, BANDS) == 3 and band_of(50.0, BANDS) == 4
    assert band_of(0.5, GATE_BANDS) == -1 and band_of(1.35, GATE_BANDS) == 0
    # roi_of: 100円買いで平均払戻120円 → 120%
    assert abs(roi_of(np.array([100.0, 140.0])) - 120.0) < 1e-9
    # ★ゲート2の性質: 仮説が偽（無作為2分割）なら主判定は0を返す
    rng = np.random.default_rng(0)
    pay = rng.choice([0.0, 800.0], size=200_000, p=[0.875, 0.125])
    half = len(pay) // 2
    a, b = pay[:half], pay[half:]
    _, _, ma, sa = cell_stats(a, None)
    _, _, mb, sb = cell_stats(b, None)
    d = ma - mb
    se = math.sqrt(sa ** 2 + sb ** 2)
    print(f"★ゲート2の自己テスト: 無作為2分割の差 {d:+.2f}円 "
          f"(SE {se:.2f}) → **|差| < 3SE なら0を返している**: "
          f"{'★OK' if abs(d) < 3 * se else '⚠NG'}")
    ok &= abs(d) < 3 * se
    # Bonferroni
    assert zq(ALPHA / NCMP) > zq(ALPHA / 5)
    print(f"★比較数 {NCMP} → z = {zq(ALPHA / NCMP):.3f}（NEXT_ANAの5比較なら "
          f"{zq(ALPHA / 5):.3f}・**厳しい側を採る**）")
    print("★自己テスト: " + ("全部OK" if ok else "⚠NG"))
    return 0 if ok else 1


def main():
    z = zq(ALPHA / NCMP)
    print("(174) ★★「差が大きい穴馬」を1頭の札（単勝/複勝）で買う")
    banner()

    races = {r["rid"]: r for r in load_races()}
    print(f"配当A {len(races):,}レース")

    # ───────── ゲート1 ─────────
    rows, bad = gate1(list(races.values()))
    print(f"\n⚠**ゲート1（判定基準32）**: (88)③④を別パーサで再現・許容±{GATE_TOL:.0f}pt")
    print(f"{'帯':<12}{'頭数':>10}{'実測ROI':>10}{'(88)':>9}{'差':>9}{'判定':>8}")
    for nm, n, roi, known, dd, ok in rows:
        print(f"{nm:<12}{n:>10,}{roi:>9.1f}%{known:>8.1f}%{dd:>+8.1f}pt"
              f"{'★立った' if ok else '⚠落ちた':>8}")
    if bad:
        if bad == [NARROW]:
            print(f"\n⚠**{NARROW}だけが落ちた**。**判定基準37: 対照が落ちたら、まず対照の"
                  f"定式化を疑え**——")
            print(f"　**(88)自身のこの帯のSEは約2.9pt＝±{GATE_TOL:.0f}ptはほぼ1σ**。"
                  f"**装置の異常ではなく、この帯の許容幅が測定誤差より狭い**。")
        print("\n⚠⚠**ゲート1が落ちた。以降を読まない**（事前登録どおり）。")
        return

    # ───────── モデル ─────────
    MODEL_DIR, PAR = CAPACITY["l2"]
    d = F.to_model(F.load_files())
    f = F.build_features(d)
    keep = (f["n_prior"] >= 1) & d["odds"].notna() & (d["odds"] > 0)
    d, f = d[keep].reset_index(drop=True), f[keep].reset_index(drop=True)
    y = (d["finish"] <= 3).astype(int).to_numpy()
    fx, _ = F.encode_categoricals(f)
    fx = add_odds_features(fx, d["odds"].to_numpy(float), d["raceid"].to_numpy())
    cut = d["date"].quantile(0.3)
    tr, te = (d["date"] < cut).to_numpy(), (d["date"] >= cut).to_numpy()
    print(f"\n学習 {tr.sum():,} / 検証 {te.sum():,}・分割 {cut.date()}（3シード平均）")
    ms = fit_seeds(fx[tr], y[tr], 3, PAR)
    p = np.mean([m.predict_proba(fx[te])[:, 1] for m in ms], axis=0)
    sub = d.loc[te, ["raceid", "umaban", "odds", "date"]].copy()
    sub["p"] = p

    # ───────── 馬ごとの行を作る ─────────
    rec = {k: [] for k in ("odds", "gap", "date", "tan", "fuku", "rid",
                           "top1", "pop", "nh")}
    nrace = nsmall = 0
    for rid, g in sub.groupby("raceid"):
        r = races.get(str(rid))
        if r is None:
            continue
        nums = {u for u, _, _ in r["horses"]}
        if len(nums) < MIN_HORSES:
            nsmall += 1
            continue
        gg = g[g["umaban"].astype(int).isin(nums)]
        if len(gg) < MIN_HORSES:
            continue
        od = gg["odds"].to_numpy(float)
        pv = gg["p"].to_numpy(float)
        if not np.isfinite(od).all() or (od <= 0).any() or pv.sum() <= 0:
            continue
        share = pv / pv.sum()
        mk = (1.0 / od) / (1.0 / od).sum()
        gap = share - mk
        # 記述用: モデル確率1位か / 人気順位(1=1番人気) / 頭数
        is_top1 = np.zeros(len(pv), bool)
        is_top1[int(np.argmax(pv))] = True
        pop = np.argsort(np.argsort(od)) + 1
        ok = True
        tv, fv = [], []
        for u in gg["umaban"].astype(int):
            a = payoff(r, "単勝", [int(u)])
            b = payoff(r, "複勝", [int(u)])
            if a is None or b is None:
                ok = False
                break
            tv.append(a)
            fv.append(b)
        if not ok:
            continue
        nrace += 1
        rec["odds"].append(od)
        rec["gap"].append(gap)
        rec["date"].append(gg["date"].to_numpy())
        rec["tan"].append(np.asarray(tv, float))
        rec["fuku"].append(np.asarray(fv, float))
        rec["rid"].append(np.full(len(od), str(rid)))
        rec["top1"].append(is_top1)
        rec["pop"].append(pop)
        rec["nh"].append(np.full(len(od), len(od)))
    for k in rec:
        rec[k] = np.concatenate(rec[k]) if rec[k] else np.array([])
    N = len(rec["odds"])
    print(f"★突き合わせ {nrace:,}レース / {N:,}頭"
          f"（⚠**{MIN_HORSES}頭未満で外した {nsmall:,}レース**）\n")

    bidx = np.array([band_of(o, BANDS) for o in rec["odds"]])
    med_date = np.median(rec["date"].astype("datetime64[D]").astype(int))
    years = rec["date"].astype("datetime64[Y]").astype(int) + 1970

    # ───────── 記述: 15マス ─────────
    print("■ 記述: **オッズ帯 × 差の3段**（★主判定は下の10比較だけ）")
    print("　★**軸は無い。レースの選別も無い**（(112)裾2%も除外40%も載っていない）。"
          "**選別は馬の単位だけ**")
    print(f"{'帯':<9}{'群':<8}{'頭数':>9}{'頭/R':>7}{'平均オッズ':>11}{'人気中央':>9}"
          f"{'モデル1位率':>12}{'単勝ROI':>9}{'複勝ROI':>9}{'複100円率':>11}")
    cells = {}
    for bi, (bn, lo, hi) in enumerate(BANDS):
        m = bidx == bi
        if m.sum() < 100:
            print(f"{bn:<9}⚠標本 {m.sum()} が少なすぎる")
            continue
        gp = rec["gap"][m]
        q_hi, q_lo = np.quantile(gp, 1 - TAILQ), np.quantile(gp, TAILQ)
        grp = {"★上位10%": gp >= q_hi, "中位": (gp > q_lo) & (gp < q_hi), "下位10%": gp <= q_lo}
        for gn, gm in grp.items():
            idx = np.where(m)[0][gm]
            tanp, fukp, odd = rec["tan"][idx], rec["fuku"][idx], rec["odds"][idx]
            floor = 100.0 * np.mean(fukp == 100.0)
            t1 = 100.0 * np.mean(rec["top1"][idx])
            pm = np.median(rec["pop"][idx])
            print(f"{bn if gn=='★上位10%' else '':<9}{gn:<8}{len(idx):>9,}"
                  f"{len(idx)/nrace:>7.2f}{odd.mean():>10.1f}倍{pm:>8.0f}番"
                  f"{t1:>11.1f}%{roi_of(tanp):>8.1f}%{roi_of(fukp):>8.1f}%"
                  f"{floor:>10.1f}%")
            if gn == "★上位10%":
                nr = len(set(rec["rid"][idx]))
                print(f"{'':<17}└ **買うレース {nr:,} / {nrace:,} = "
                      f"{100*nr/nrace:.1f}%**（★**軸ではなく、この帯にこの馬が居るときだけ**）")
            cells[(bi, gn)] = idx

    # ───────── 主判定 ─────────
    print(f"\n■ ★★主判定: **各帯で「差の上位10% − 下位10%」**"
          f"（**{NCMP}比較・Bonferroni α={ALPHA}/{NCMP}・z={z:.3f}**）")
    print("　★ゲート2: **仮説が偽なら両群は同じ帯の無作為2分割＝期待値0を返す**。"
          "**頭数は両群同数**")
    print(f"\n{'券種':<6}{'帯':<9}{'上位n':>8}{'下位n':>8}{'1点損益差':>11}"
          f"{'99%CI(Bonf)':>21}{'判定':>14}")
    verdict = {}
    for kind, key in ((k, "tan" if k == "単勝" else "fuku") for k in KINDS):
        for bi, (bn, lo, hi) in enumerate(BANDS):
            if (bi, "★上位10%") not in cells:
                continue
            hi_i, lo_i = cells[(bi, "★上位10%")], cells[(bi, "下位10%")]
            nh, _, mh, sh = cell_stats(rec[key][hi_i], z)
            nl, _, ml, sl = cell_stats(rec[key][lo_i], z)
            dd = mh - ml
            se = math.sqrt(sh ** 2 + sl ** 2)
            hw = z * se
            if hw > UNDECIDABLE:
                v = f"⚠判定不能(±{hw:.0f})"
            elif abs(dd) > hw:
                v = "★差がある"
            else:
                v = "⚠検出できない"
            verdict[(kind, bn)] = (dd, hw, v)
            print(f"{kind:<6}{bn:<9}{nh:>8,}{nl:>8,}{dd:>+10.1f}円"
                  f"{f'[{dd-hw:+.1f},{dd+hw:+.1f}]':>21}{v:>14}")

    # ───────── 採用条件 ─────────
    sig_f = [bn for (k, bn), (dd, hw, v) in verdict.items()
             if k == "複勝" and v == "★差がある" and dd > 0]
    agree = [bn for bn in sig_f if verdict.get(("単勝", bn), (0,))[0] > 0]
    print(f"\n■ ★採用条件（判定基準39/40/41）")
    print(f"　1. 複勝で2帯以上が正に有意 … **{len(sig_f)}帯** {sig_f if sig_f else ''}"
          f" → {'★満たす' if len(sig_f) >= 2 else '⚠満たさない'}")
    print(f"　2. 同じ帯で単勝も同符号   … **{len(agree)}帯** {agree if agree else ''}")
    if len(sig_f) < 2:
        print("\n★★**結論: 採用条件1を満たさない＝陰性**。")
        print("⚠**ただし経路は弱い（単勝由来）ので「閉じた」とは書けない**（判定基準25）。")
        print("　書けるのは「**モデルのシェアと単勝オッズの差では取れない**」まで。")
