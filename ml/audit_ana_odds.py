    # ───────── 裾の検算（通ったマスだけ） ─────────
    print(f"\n■ ★裾の検算（(77)・通った帯のみ）")
    for bn in sig_f:
        bi = [i for i, b in enumerate(BANDS) if b[0] == bn][0]
        idx = cells[(bi, "★上位10%")]
        pay = rec["fuku"][idx]
        top3 = 100.0 * np.sort(pay)[-3:].sum() / max(pay.sum(), 1e-9)
        dt = rec["date"][idx].astype("datetime64[D]").astype(int)
        h1, h2 = dt <= med_date, dt > med_date
        yr = years[idx]
        ys = sorted(set(yr))
        over = sum(1 for u in ys if roi_of(pay[yr == u]) > 100.0)
        print(f"　{bn} 複勝上位10%: ROI {roi_of(pay):.1f}% / "
              f"**上位3本が全払戻の {top3:.1f}%** / "
              f"前半 {roi_of(pay[h1]):.1f}% ・後半 {roi_of(pay[h2]):.1f}% / "
              f"**100%超の年 {over}/{len(ys)}**")
    print("\n⚠**陽性でも、ROIが100%を超えなければ運用の候補にならない**（事前登録）。")
    print("⚠**枠連の運用には触れない**。**設定変更は提案しない**。")


